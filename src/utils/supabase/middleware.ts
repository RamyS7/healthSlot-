import { createServerClient, type CookieOptions } from '@supabase/ssr'
import { NextResponse, type NextRequest } from 'next/server'

export async function updateSession(request: NextRequest) {
  let response = NextResponse.next({
    request: {
      headers: request.headers,
    },
  })

  const supabase = createServerClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!,
    {
      cookies: {
        get(name: string) {
          return request.cookies.get(name)?.value
        },
        set(name: string, value: string, options: CookieOptions) {
          request.cookies.set({
            name,
            value,
            ...options,
          })
          response = NextResponse.next({
            request: {
              headers: request.headers,
            },
          })
          response.cookies.set({
            name,
            value,
            ...options,
          })
        },
        remove(name: string, options: CookieOptions) {
          request.cookies.set({
            name,
            value: '',
            ...options,
          })
          response = NextResponse.next({
            request: {
              headers: request.headers,
            },
          })
          response.cookies.set({
            name,
            value: '',
            ...options,
          })
        },
      },
    }
  )

  const { data: { user } } = await supabase.auth.getUser()

  // Authorization checks based on routes
  const isDashboardRoute = request.nextUrl.pathname.startsWith('/dashboard')
  const isBookRoute = request.nextUrl.pathname.startsWith('/book')

  if (!user && (isDashboardRoute || isBookRoute)) {
    // Redirect unauthenticated users to login if they try to access protected routes
    return NextResponse.redirect(new URL('/login', request.url))
  }

  if (user && isDashboardRoute) {
    // Check if user has provider role
    const { data: userData } = await supabase
      .from('users')
      .select('role')
      .eq('id', user.id)
      .single()

    if (userData?.role !== 'provider') {
      // Redirect users without provider role away from dashboard
      return NextResponse.redirect(new URL('/', request.url))
    }
  }

  return response
}
